from __future__ import annotations

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import Platform
from homeassistant.core import HomeAssistant
from homeassistant.helpers import entity_registry as er

from .const import CONF_ENABLED_SENSORS
from .coordinator import MarineWeatherCoordinator

PLATFORMS: list[Platform] = [
    Platform.SENSOR,
    Platform.BINARY_SENSOR,
    Platform.NUMBER,
]

type MarineWeatherConfigEntry = ConfigEntry[MarineWeatherCoordinator]


async def async_setup_entry(
    hass: HomeAssistant, entry: MarineWeatherConfigEntry
) -> bool:
    """Set up Open-Meteo Marine Weather from a config entry."""
    coordinator = MarineWeatherCoordinator(hass, entry)
    await coordinator.async_config_entry_first_refresh()

    entry.runtime_data = coordinator

    # No options update listener: the threshold number entities notify the
    # coordinator's listeners themselves when a value changes, which avoids
    # reloading (and visibly recreating) every entity on each adjustment.
    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    return True


async def async_unload_entry(
    hass: HomeAssistant, entry: MarineWeatherConfigEntry
) -> bool:
    """Unload a config entry."""
    return await hass.config_entries.async_unload_platforms(entry, PLATFORMS)


async def async_migrate_entry(
    hass: HomeAssistant, entry: MarineWeatherConfigEntry
) -> bool:
    """Migrate an old config entry to the current schema."""
    if entry.version > 1:
        # Written by a newer release than this one; refuse rather than guess.
        return False

    if entry.minor_version < 2:
        # Imported here rather than at module scope because sensor.py imports
        # MarineWeatherConfigEntry from this module.
        from .sensor import PREVIOUS_DEFAULT_SENSOR_KEYS, SENSOR_DESCRIPTIONS

        stored = entry.data.get(CONF_ENABLED_SENSORS)

        # Minor version 1 kept no record of whether the stored sensor list was
        # a deliberate choice. Entries with no list at all (created before the
        # confirm step existed) and entries holding exactly the old default set
        # are opted into every sensor; any other list was a deselection the
        # user made by hand, so it is carried over untouched.
        if stored is None or set(stored) == PREVIOUS_DEFAULT_SENSOR_KEYS:
            enabled_keys = [description.key for description in SENSOR_DESCRIPTIONS]
        else:
            enabled_keys = list(stored)

        hass.config_entries.async_update_entry(
            entry,
            data={**entry.data, CONF_ENABLED_SENSORS: enabled_keys},
            minor_version=2,
        )

    if entry.minor_version < 3:
        from .sensor import REMOVED_SENSOR_KEYS

        # These sensors read null from Open-Meteo everywhere, so 2.3.0 dropped
        # them. Existing entries still hold their registry entries and may list
        # them in enabled_sensors; clear both so they do not linger as
        # permanently-unavailable entities.
        registry = er.async_get(hass)
        for key in REMOVED_SENSOR_KEYS:
            entity_id = registry.async_get_entity_id(
                Platform.SENSOR, entry.domain, f"{entry.unique_id}_{key}"
            )
            if entity_id:
                registry.async_remove(entity_id)

        data = entry.data
        stored = data.get(CONF_ENABLED_SENSORS)
        if stored is not None:
            pruned = [key for key in stored if key not in REMOVED_SENSOR_KEYS]
            if pruned != stored:
                data = {**data, CONF_ENABLED_SENSORS: pruned}

        hass.config_entries.async_update_entry(entry, data=data, minor_version=3)

    return True
